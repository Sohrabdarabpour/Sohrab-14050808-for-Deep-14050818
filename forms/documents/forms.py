from flask_wtf import FlaskForm
from wtforms import StringField, TextAreaField, IntegerField, SubmitField
class DocumentForm(FlaskForm):
    code_dfc = StringField("کد DFC")
    date_letter = StringField("تاریخ نامه")
    automation_number = StringField("شماره نامه اتوماسیون")
    contractor_letter_number = StringField("شماره نامه پیمانکار")
    subject = TextAreaField("موضوع نامه")
    contract_number = StringField("شماره قرارداد ریالی")
    project_name = StringField("نام پروژه")
    contractor = StringField("پیمانکار")
    area = StringField("ناحیه")
    date_received = StringField("تاریخ دریافت")
    date_referral = StringField("تاریخ ارجاع")
    expert_name = StringField("نام کارشناس")
    user_id = IntegerField("شناسه کارشناس")
    unit = StringField("واحد")
    document_group = StringField("گروه سند")
    sub_group = StringField("زیر گروه")
    deadline = StringField("موعد تحویل")
    request_complete_docs = StringField("تاریخ درخواست تکمیل مدارک")
    complete_docs_by_contractor = StringField("تاریخ تکمیل مدارک توسط پیمانکار")
    doc_response_status = StringField("وضعیت پاسخ مدرک")
    response_announce_date = StringField("تاریخ اعلام پاسخ")
    final_letter_number = StringField("شماره نامه نهایی")
    final_delay = StringField("تاخیر نهایی")
    colleague = StringField("همکار")
    Responsible_Party = StringField("مسئول رسیدگی")
    submit = SubmitField("ذخیره")